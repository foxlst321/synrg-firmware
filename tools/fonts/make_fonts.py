#!/usr/bin/env python3
"""Generates synrg/SynFonts.h: small Adafruit-GFX bitmap fonts rendered from
DejaVu Sans (1-bit, hinted). Run from the repo root: python3 tools/fonts/make_fonts.py"""
from PIL import Image, ImageDraw, ImageFont

FONTS = [
    ("SynSmall",     "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 10),
    ("SynSmallBold", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 10),
]

def build(name, path, size):
    font = ImageFont.truetype(path, size)
    bits, glyphs = [], []
    for code in range(0x20, 0x7F):
        ch = chr(code)
        im = Image.new("1", (40, 40), 0)
        d = ImageDraw.Draw(im); d.fontmode = "1"
        d.text((10, 25), ch, font=font, fill=1, anchor="ls")   # baseline at y=25
        box = im.getbbox()
        adv = int(round(font.getlength(ch)))
        offset = len(bits) // 8 if len(bits) % 8 == 0 else None
        if len(bits) % 8: bits += [0] * (8 - len(bits) % 8)
        offset = len(bits) // 8
        if box is None:
            glyphs.append((offset, 0, 0, adv, 0, 0)); continue
        x0, y0, x1, y1 = box
        for y in range(y0, y1):
            for x in range(x0, x1):
                bits.append(1 if im.getpixel((x, y)) else 0)
        glyphs.append((offset, x1 - x0, y1 - y0, adv, x0 - 10, y0 - 25))
    if len(bits) % 8: bits += [0] * (8 - len(bits) % 8)
    data = [sum(b << (7 - i) for i, b in enumerate(bits[n:n + 8])) for n in range(0, len(bits), 8)]
    out = [f"const uint8_t {name}Bitmaps[] PROGMEM = {{"]
    for n in range(0, len(data), 16):
        out.append("  " + ", ".join(f"0x{b:02X}" for b in data[n:n + 16]) + ",")
    out.append("};")
    out.append(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for i, g in enumerate(glyphs):
        out.append("  {%d, %d, %d, %d, %d, %d},  // '%s'" % (*g, chr(0x20 + i) if chr(0x20 + i) != "\\" else "backslash"))
    out.append("};")
    out.append(f"const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, 0x20, 0x7E, {size + 2}}};")
    return "\n".join(out)

header = """// GENERATED by tools/fonts/make_fonts.py -- do not edit by hand.
// Small UI fonts for SynRG, rendered from DejaVu Sans / DejaVu Sans Bold at
// 10 px. DejaVu fonts are (c) Bitstream (Bitstream Vera license) and public
// domain changes by the DejaVu team; redistribution is permitted.
#pragma once
#include <Adafruit_GFX.h>

"""
open("synrg/SynFonts.h", "w").write(header + "\n\n".join(build(*f) for f in FONTS) + "\n")
print("wrote synrg/SynFonts.h")
